#集合去重
list=[1,1,1,2,2,2,3,3,4]
s1=set(list)
print(s1)
#集合交并差集
s2={3,4,5,6,7}
print("交集：",s1&s2)
print("并集：",s1|s2)
print("差集：",s1-s2)
